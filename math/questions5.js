// 一连串的等量替换
function wtChain() {
  // 从重到轻排好，挑 4 样（量词跟着走）
  const pool = pick([[['个大西瓜'], ['个小西瓜'], ['个菠萝'], ['个苹果'], ['个橘子'], ['颗草莓']], [['头小猪'], ['只大鹅'], ['只鸭子'], ['只小鸡'], ['只小鸟']], [['袋大米'], ['袋面粉'], ['盒饼干'], ['包薯片']]]).map(x => x[0])
  const idx = shuffle(pool.map((_, i) => i)).slice(0, 4).sort((x, y) => x - y), [A, B, C, D] = idx.map(i => pool[i])
  const k1 = R(2, 4), k2 = R(2, 4), k3 = R(2, 3), three = Math.random() < 0.45
  const bare = s => s.slice(1)
  if (three) return input('hard', `1 ${A}和 ${k1} ${B}一样重，1 ${B}和 ${k2} ${C}一样重，1 ${C}和 ${k3} ${D}一样重。1 ${A}和几${D[0]}${bare(D)}一样重？`, k1 * k2 * k3,
    `一步一步替换：\n1 ${A} = ${k1} ${B}\n= ${k1} × ${k2} = ${k1 * k2} ${C}\n= ${k1 * k2} × ${k3} = ${k1 * k2 * k3} ${D}。`, null, D[0])
  const m = R(2, 3)
  return input('hard', `${m} ${A}和 ${m * k1} ${B}一样重，1 ${B}和 ${k2} ${C}一样重。1 ${A}和几${C[0]}${bare(C)}一样重？`, k1 * k2,
    `先算 1 ${A}：${m * k1} ÷ ${m} = ${k1}，1 ${A} = ${k1} ${B}；\n再替换：${k1} × ${k2} = ${k1 * k2}，1 ${A} = ${k1 * k2} ${C}。`, null, C[0])
}

