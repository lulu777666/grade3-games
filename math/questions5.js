// 数一数图里的角
function angleCountFig() {
  const n = R(3, 5), kinds = []
  // 从同一个顶点 O 引出 n 条射线
  const base = R(0, 2) * 10, gaps = Array.from({ length: n - 1 }, () => R(3, 6) * 10)
  let a = base; const angs = [a]; gaps.forEach(g => { a += g; angs.push(a) })
  if (a > 175) return angleCountFig()
  for (let i = 0; i < n; i++) for (let j = i + 1; j < n; j++) kinds.push(angs[j] - angs[i])
  // 合起来的角不要太接近直角（眼睛不好分辨），除非正好是直角
  if (kinds.some(d => d !== 90 && Math.abs(d - 90) < 20)) return angleCountFig()
  const rad = d => d * Math.PI / 180, L = 125
  const ends = angs.map(d => [L * Math.cos(rad(d)), -L * Math.sin(rad(d))]), xs = [0, ...ends.map(e => e[0])], ys = [0, ...ends.map(e => e[1])]
  const cx = 150 - (Math.min(...xs) + Math.max(...xs)) / 2, cy = 80 - (Math.min(...ys) + Math.max(...ys)) / 2
  const lines = ends.map(([x, y]) => `<line x1="${cx.toFixed(1)}" y1="${cy.toFixed(1)}" x2="${(cx + x).toFixed(1)}" y2="${(cy + y).toFixed(1)}"/>`).join('')
  const cnt = n * (n - 1) / 2
  const nr = kinds.filter(d => d === 90).length, na = kinds.filter(d => d < 90).length, no = kinds.filter(d => d > 90).length
  const want = pick(['all', 'all', 'acute', 'obtuse']), ans = want === 'all' ? cnt : want === 'acute' ? na : no
  const fig = `<svg viewBox="0 0 300 175" class="fig wide"><g stroke="#4a5bd4" stroke-width="3" stroke-linecap="round">${lines}</g><circle cx="${cx.toFixed(1)}" cy="${cy.toFixed(1)}" r="4" fill="#333"/><text x="${(cx - 6).toFixed(1)}" y="${(cy + 20).toFixed(1)}" font-size="16" fill="#555">O</text></svg>`
  return input('hard', `从点 O 引出 ${n} 条射线（如图）。图中一共有几个${want === 'all' ? '角' : want === 'acute' ? '锐角（小于直角）' : '钝角（大于直角）'}？${want === 'all' ? '' : '\n提示：相邻两条射线之间的小角都是锐角。'}`, ans,
    `先数一共有几个角：每条射线和它后面的射线各组成一个角，\n${Array.from({ length: n - 1 }, (_, i) => n - 1 - i).join(' + ')} = ${cnt}（个）。${want === 'all' ? '' : `\n这些角里：锐角 ${na} 个，直角 ${nr} 个，钝角 ${no} 个（几个小角合起来，就可能超过直角）。`}`, fig, '个')
}

